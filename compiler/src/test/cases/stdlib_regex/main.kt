fun main() {
    val digits = Regex("\\d+")
    println(digits.containsMatchIn("abc123"))
    println(digits.matches("123"))
    println(digits.matches("123a"))
    println(digits.find("a12b345")?.value)
    println(digits.find("a12b345")?.range)
    println(digits.find("a12b345", 3)?.value)
    println(digits.findAll("a12b345c6").map { it.value }.toList())
    println(digits.findAll("a12b345c6").count())
    println(digits.replace("a1b22c333", "#"))
    println(digits.replace("a1b22c333") { "<" + it.value.length + ">" })
    println(digits.replaceFirst("a1b22", "N"))
    println(digits.split("a1b22c"))
    println("a1b22".replace(Regex("[0-9]"), "_"))
    println("hello world".contains(Regex("o w")))
    println("abc".matches(Regex("[a-c]+")))
    println("one two  three".split(Regex("\\s+")))
    println("a1b2".toRegex().findAll("a1b2").map { it.value }.joinToString("|"))

    val date = Regex("(\\d{4})-(\\d{2})-(\\d{2})")
    val m = date.find("on 2024-03-15 ok")!!
    println(m.value)
    println(m.groupValues)
    println(m.groups[1]?.value)
    println(m.groups.size)
    val (y, mo, d) = m.destructured
    println("$d/$mo/$y")
    println(m.range.first)
    println(date.find("none"))

    val named = Regex("(\\w+)=(\\w+)")
    val kv = named.find("a=1, b=2")!!
    println(kv.groups[1]?.value)
    println(kv.groups[2]?.value)
    println(named.findAll("a=1, b=2").map { it.groupValues[1] to it.groupValues[2] }.toList())
    println(named.replace("a=1, b=2", "$2:$1"))

    val opt = Regex("(a)(b?)")
    println(opt.find("a")!!.groupValues)
    println(opt.find("a")!!.groups[2]?.value?.isEmpty())

    println(Regex("a.c", RegexOption.IGNORE_CASE).matches("AbC"))
    println(Regex("^b").findAll("b\nbb").count())
    println(Regex("a+b").pattern)
    println(Regex.escape("a.b*c"))
    println(Regex("colou?r").findAll("color colour colr").map { it.value }.toList())
    println(Regex("(\\w)\\1").find("hello")?.value)
    println(Regex("[^aeiou\\s]+").findAll("hello world").map { it.value }.toList())
    println(Regex("\\bfoo\\b").containsMatchIn("a foo b"))
    println(Regex("x*").split("axxb"))
    println(Regex("a+?").find("aaa")?.value)
    println(Regex("\\$\\d+\\.\\d{2}").find("cost: $12.50 total")?.value)
}
