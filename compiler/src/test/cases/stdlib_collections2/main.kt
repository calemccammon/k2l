fun ordering() {
    val xs = listOf(3, 1, 2)
    val words = listOf("bb", "a", "ccc")
    println(xs.sortedBy { -it })
    println(xs.sortedWith(compareBy<Int> { it % 2 }.thenBy { it }))
    println(xs.sortedWith(compareByDescending<Int> { it }))
    println(xs.sortedWith(Comparator { a, b -> b - a }))
    println(words.sortedWith(compareBy({ it.length }, { it })))
    println(listOf(3, null, 1).sortedWith(nullsFirst()))
    println(listOf(3, null, 1).sortedWith(nullsLast()))
    println(xs.sortedDescending())
    println(words.maxBy { it.length })
    println(words.minByOrNull { it.length })
    println(words.maxWithOrNull(compareBy { it.length }))
    println(xs.reversed())
}

fun grouping() {
    val words = listOf("bb", "a", "ccc", "dd")
    println(words.groupBy { it.length })
    println(words.groupingBy { it.length }.eachCount())
    println(words.associateBy { it.length })
    println(words.associate { it to it.length })
    println(words.partition { it.length > 1 })
    println(words.zip(listOf(1, 2, 3)))
    println(words.zip(listOf(1, 2, 3)).unzip())
    println(words.distinctBy { it.length })
}

fun windows() {
    val xs = listOf(3, 1, 2, 5, 4)
    println(xs.chunked(2))
    println(xs.chunked(2) { it.sum() })
    println(xs.windowed(3))
    println(xs.windowed(2, 2, true))
    println(xs.zipWithNext())
    println(xs.zipWithNext { a, b -> a + b })
    println(xs.scan(0) { a, b -> a + b })
    println(xs.runningReduce { a, b -> a + b })
    println(xs.foldIndexed(0) { i, a, b -> a + b * i })
    println(xs.foldRight(0) { a, b -> a - b })
    println(xs.foldRightIndexed(0) { i, a, b -> a + b * i })
    println(xs.reduceRight { a, b -> a - b })
    println(xs.reduceOrNull { a, b -> a + b })
}

fun slicing() {
    val xs = listOf(3, 1, 2, 5, 4)
    println(xs.take(2))
    println(xs.drop(2))
    println(xs.takeLast(2))
    println(xs.dropLast(2))
    println(xs.takeWhile { it > 1 })
    println(xs.dropWhile { it > 1 })
    println(xs.takeLastWhile { it > 1 })
    println(xs.dropLastWhile { it > 1 })
    println(xs.slice(1..3))
    println(xs.slice(listOf(0, 4)))
    println(xs.elementAtOrNull(9))
    println(xs.elementAtOrElse(9) { -1 })
    println(xs.getOrElse(9) { -2 })
    println(xs.indexOfFirst { it > 2 })
    println(xs.indexOfLast { it > 2 })
    println(xs.lastIndexOf(2))
    println(xs.asReversed())
}

fun aggregates() {
    val xs = listOf(3, 1, 2)
    println(xs.sumOf { it * 2 })
    println(xs.sumOf { it.toDouble() })
    println(xs.average())
    println(xs.maxOf { it * 2 })
    println(xs.minOfOrNull { it * 2 })
    println(xs.count { it > 1 })
    println(emptyList<Int>().maxOrNull())
    println(xs.joinToString(", ", "[", "]"))
    println(xs.joinToString(separator = "-") { "<$it>" })
    println(xs.joinToString(limit = 2, truncated = "..."))
    println(listOf(listOf(1), listOf(2, 3)).flatten())
    println(xs.flatMap { listOf(it, it) })
    println(xs.mapIndexedNotNull { i, v -> if (i > 0) v else null })
    println(xs.mapIndexedTo(mutableListOf()) { i, v -> i + v })
    println(xs + 4)
    println(xs + listOf(4, 5))
    println(xs - 1)
    println(xs - listOf(1, 2))
    println(xs.containsAll(listOf(1, 2)))
}

fun mutation() {
    val ml = mutableListOf(5, 3, 4, 1)
    println(ml.removeFirstOrNull())
    println(ml.removeLastOrNull())
    println(ml)
    ml.addAll(listOf(9, 8))
    ml.retainAll { it > 3 }
    println(ml)
    ml.sortDescending()
    println(ml)
    ml.add(1, 100)
    ml.removeAt(0)
    println(ml)
    ml.replaceAll { it + 1 }
    println(ml)
    ml.removeAll { it > 100 }
    println(ml)
    val it = mutableListOf(5, 3, 4).iterator()
    val kept = mutableListOf<Int>()
    val all = mutableListOf(5, 3, 4)
    val iter = all.iterator()
    while (iter.hasNext()) {
        val v = iter.next()
        if (v == 3) iter.remove() else kept.add(v)
    }
    println(all)
    println(kept)
    println(it.next())
}

fun misc() {
    val mixed: List<Any> = listOf(1, "a", 2, "b", 3.5)
    println(mixed.filterIsInstance<Int>())
    println(mixed.filterIsInstance<String>())
    val mp = mapOf("a" to 1, "b" to 2, "c" to 3)
    println(mp.filterTo(mutableMapOf()) { it.value > 1 })
    println(mp.filter { it.value > 1 })
    println(mp.mapValues { it.value * 2 })
    println(mp.mapKeys { it.key.uppercase() })
    println(mp.entries.sortedByDescending { it.value }.map { it.key })
    println(mp.maxByOrNull { it.value }?.key)
    println(mp.toList())
    println(mp.getOrDefault("z", 0))
    println(mapOf<String, Int>().ifEmpty { mapOf("e" to 0) })
    println(mp.minus("a"))
    println(mp + ("d" to 4))
    println(arrayOf(3, 1, 2).sortedArray().toList())
    println(intArrayOf(3, 1, 2).sum())
    println(Array(2) { Array(2) { it } }.contentDeepToString())
    println(emptyList<Int>().ifEmpty { listOf(0) })
}

