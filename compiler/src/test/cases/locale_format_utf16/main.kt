import java.util.Locale

fun main() {
    val tr = Locale("tr", "TR")
    println(String.format(tr, "%S", "istanbul iI"))
    println(String.format(tr, "%s", "istanbul iI"))
    println(String.format(tr, "%10S|%-10S|", "ii", "ıİ"))
    println(String.format(tr, "%C %c", 'i', 'i'))
    println("%S and %S".format(tr, "i", "ı"))
    println(String.format(Locale("az"), "%S", "iı"))
    println(String.format(Locale("lt"), "%S", "i̇"))
    println(String.format(Locale.ROOT, "%S", "istanbul straße"))
    println(String.format(Locale.US, "%S %C", "straße ǆ", 'ß'))
    println(String.format(Locale.GERMANY, "%S", "ñandú straße"))
    println("%S".format("ǰ ŉ ﬁ"))
    println(String.format("%S|%10S|%-8S|", "é", "ü", "ö"))
    println(String.format("%B %b", true, false))
    println(String.format(tr, "%B", "istanbul" == "istanbul"))
    println(String.format(Locale.FRANCE, "%S %,d", "été", 1234567))
    println(String.format(tr, "%S %,.2f", "i", 1234567.891))
    val locales = listOf(Locale.US, tr, Locale("az", "AZ"), Locale.GERMANY)
    println(locales.map { String.format(it, "%S", "iI") })
    println(String.format("%s %S", "ß", "ß"))
    println(String.format(Locale("ar", "EG"), "%S %d", "abc", 42))
}
