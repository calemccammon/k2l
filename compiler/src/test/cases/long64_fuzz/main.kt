fun f(a: Long, b: Long, n: Int) {
    val sb = StringBuilder()
    sb.append(a).append(' ').append(b).append(" | ")
    sb.append(a + b).append(' ').append(a - b).append(' ').append(a * b).append(' ').append(a / b).append(' ').append(a % b).append(" | ")
