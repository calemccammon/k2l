import java.util.PriorityQueue
import java.util.TreeSet
import kotlin.math.roundToLong

fun main() {
    val big = 5_000_000_000_000_000_000L
    val max = Long.MAX_VALUE
    val min = Long.MIN_VALUE
    val arr = longArrayOf(max, 5L, min, big, -3L, 0L)
    arr.sort()
    println(arr.toList())
    arr.sortDescending()
    println(arr.toList())
    val list = mutableListOf(max, 5L, min, big, -3L, 0L)
    list.sort()
    println(list)
    list.sortDescending()
    println(list)
    list.sortBy { -it }
    println(list)
    list.sortWith(compareBy { it % 10 })
    println(list)
    println(list.sortedWith(compareByDescending<Long> { it }.thenBy { it }))
    println(list.sortedBy { it })
    println(list.binarySearch(5L))
    println(list.sorted().binarySearch(big))
    println(java.util.Collections.max(list))
    println(java.util.Collections.min(list))
    val ts = TreeSet<Long>()
    ts.addAll(list)
    println(ts)
    println(ts.first())
    println(ts.last())
    println(ts.higher(5L))
    println(ts.lower(big))
    val pq = PriorityQueue<Long>()
    pq.addAll(list)
    val out = mutableListOf<Long>()
    while (pq.isNotEmpty()) out.add(pq.poll())
    println(out)
    val dq = ArrayDeque<Long>()
    dq.addLast(big)
    dq.addFirst(max)
    println(dq.removeFirst() - dq.removeLast())
    println(list.min())
    println(list.max())
    println(list.minOrNull())
    println(list.indexOf(min))
    println(list.lastIndexOf(max))
    println(list.remove(big))
    println(list)
    println(list.contains(big))
    println((list + big).distinct().size)
    println(list.toSet().size)
    println(list.chunked(2))
    println(list.windowed(2).map { it[0] - it[1] })
    println(list.zipWithNext { a, b -> a + b })
    println(list.runningFold(0L) { a, b -> a + b })
    println(list.scan(1L) { a, b -> a xor b })
    println(list.partition { it > 0 })
    println(list.groupBy { it > 0 }.mapValues { (_, v) -> v.sum() })
    println(list.associateBy { it % 7 })
    println(list.reversed())
    println(list.takeWhile { it != 5L })
    println(list.firstOrNull { it > big })
    println(list.last { it < 0 })
    println(list.sumOf { it })
    println(1e19.roundToLong())
    println(-1e19.roundToLong())
    println(4.611686018427388E18.roundToLong())
    println(2.5.roundToLong())
    println(Math.round(1e19))
    println(Math.round(-2.5))
    println(Math.round(4.611686018427388E18))
    println(java.util.Arrays.toString(arr))
    java.util.Arrays.sort(arr)
    println(arr.toList())
    println(arr.joinToString())
    println(arr.map { it + 1 })
    println(arr.filter { it > 0 }.size)
    println(arr.indexOf(big))
    println(arr.max())
    println(arr.copyOf(8).toList())
    println(arr.copyOfRange(1, 3).toList())
    println(arr.reversedArray().toList())
    val hm = HashMap<Long, Int>()
    for ((i, k) in listOf(big, max, 17L, big + 1, min, 3L, 1L shl 40, 1L shl 33, -(1L shl 40)).withIndex()) hm[k] = i
    println(hm)
    println(hm.keys)
    println(hm.entries.first())
    val hs = HashSet(hm.keys)
    println(hs)
    println(hs.map { it % 5 }.toSet())
    val big2 = Array<Long>(3) { big * it }
    println(big2.toList())
    println(big2.sum())
}
