fun interleaving() {
    val log = mutableListOf<String>()
    val dest = sequenceOf(1, 2).map { log.add("map $it"); it * 10 }.mapTo(mutableListOf()) { log.add("to $it"); it + 1 }
    println("$dest $log")
    log.clear()
    val groups = sequenceOf(1, 2, 3).onEach { log.add("each $it") }.groupingBy { log.add("key $it"); it % 2 }.eachCount()
    println("$groups $log")
    log.clear()
    println(generateSequence(1) { it + 1 }.firstNotNullOf { log.add("try $it"); if (it > 2) it else null })
    println(log)
    println(sequenceOf(1, null).requireNoNulls().take(1).toList())
    println(runCatching { sequenceOf(1, null).requireNoNulls().toList() }.exceptionOrNull() is IllegalArgumentException)
    println(sequenceOf(1, 2).orEmpty().toList())
    val none: Sequence<Int>? = null
    println(none.orEmpty().count())
}

// transforms and keys that are false
fun falseValues() {
    println(sequenceOf(1, 2).zip(sequenceOf(2, 1)) { a, b -> a > b }.toList())
    println(sequenceOf(1, 3, 2).zipWithNext { a, b -> a > b }.toList())
    println(sequenceOf(1, 2, 3).windowed(2) { it.size > 5 }.toList())
    println(sequenceOf(1, 2, 3).groupBy({ it % 2 }, { it > 1 }))
    println(sequenceOf(1, 2, 3).associateBy({ it }, { it > 2 }))
    println(sequenceOf(3, 1, 2).maxBy { it < 2 })
    println(listOf(3, 1, 2).maxBy { it < 2 })
    println(listOf(3, 1, 2).minByOrNull { it > 2 })
    println("abcd".chunked(2) { it == "ab" })
    println("abcd".windowed(2) { it == "bc" })
}

