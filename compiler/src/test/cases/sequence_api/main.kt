// The Sequence API next to the Iterable one: terminal operations pull one element at a time (see the interleaved log),
// the ...To forms fill a destination, and maxOfWith/minOfWith on collections, arrays, maps and strings.

fun seq() = sequenceOf(3, 1, 2)
fun nullableSeq() = sequenceOf(3, null, 2)

fun sequenceFunctions() {
    println(seq().elementAtOrElse(5) { -it })
    println(seq().firstNotNullOf { if (it < 3) it * 10 else null })
    println(seq().firstNotNullOfOrNull { if (it > 5) it else null })
    println(seq().indexOfLast { it > 1 })
    println(seq().lastIndexOf(2))
    println(seq().filterIndexedTo(mutableListOf()) { i, _ -> i > 0 })
    println(sequenceOf<Any>(1, "a").filterIsInstance<String>().toList())
    println(sequenceOf<Any>(1, "a").filterIsInstanceTo(mutableListOf<Int>()))
    println(nullableSeq().filterNotNullTo(mutableListOf()))
    println(seq().filterNotTo(mutableListOf()) { it > 2 })
    println(seq().filterTo(mutableListOf()) { it > 2 })
    println(seq().associateByTo(mutableMapOf()) { it * 2 })
    println(seq().associateTo(mutableMapOf()) { it to it })
    println(seq().associateWithTo(mutableMapOf()) { it + 1 })
    println(seq().toHashSet())
    println(seq().toMutableList())
    println(seq().toMutableSet())
    println(seq().flatMap { listOf(it, it) }.toList())
    println(seq().flatMapIndexed { i, x -> listOf(i, x) }.toList())
    println(seq().flatMapTo(mutableListOf()) { listOf(it) })
    println(seq().flatMapIndexedTo(mutableListOf()) { i, x -> listOf(i + x) })
    println(seq().groupByTo(mutableMapOf()) { it % 2 })
    println(seq().groupingBy { it % 2 }.eachCount())
    println(seq().mapIndexedNotNullTo(mutableListOf()) { i, x -> if (i > 0) x else null })
    println(seq().mapIndexedTo(mutableListOf()) { i, x -> i * x })
    println(seq().mapNotNullTo(mutableListOf()) { if (it > 1) it else null })
    println(seq().mapTo(mutableListOf()) { it * 3 })
    println(seq().maxOfWith(compareBy { it }) { -it })
    println(seq().maxOfWithOrNull(compareBy { it }) { -it })
    println(seq().minOfWith(compareBy { it }) { -it })
    println(seq().minOfWithOrNull(compareBy { it }) { -it })
    println(seq().maxWith(compareBy { it }))
    println(seq().maxWithOrNull(compareBy { it }))
    println(seq().minWith(compareBy { it }))
    println(seq().minWithOrNull(compareBy { it }))
    println(seq().reduceIndexed { i, a, x -> a + i * x })
    println(seq().reduceIndexedOrNull { i, a, x -> a + i * x })
    println(seq().reduceOrNull { a, x -> a * x })
    println(emptySequence<Int>().reduceOrNull { a, x -> a * x })
    println(seq().runningFoldIndexed(0) { i, a, x -> a + i + x }.toList())
    println(seq().runningReduceIndexed { i, a, x -> a + i * x }.toList())
    println(seq().scanIndexed(1) { i, a, x -> a * x + i }.toList())
    println(seq().sumBy { it * 2 })
    println(seq().sumByDouble { it / 2.0 })
    println(seq().requireNoNulls().count())
    println(seq().minus(1).toList())
    println(seq().minus(arrayOf(1, 2)).toList())
    println(seq().minus(listOf(3)).toList())
    println(seq().minus(sequenceOf(2)).toList())
    println(seq().minusElement(3).toList())
    println(seq().plus(arrayOf(7)).toList())
    println(seq().plusElement(8).toList())
    println(seq().joinTo(StringBuilder(), "-"))
    println(seq().shuffled(kotlin.random.Random(1)).count())
    println(seq().elementAt(1))
    println(seq().take(2).sum())
    println(seq().scan(0) { a, x -> a + x }.toList())
    println(seq().zip(sequenceOf("a", "b")) { a, b -> "$a$b" }.toList())
    println(seq().windowed(2) { it.sum() }.toList())
    println(seq().chunked(2) { it.size }.toList())
    println(seq().forEachIndexed { i, x -> print("$i$x ") })
    println(seq().sortedWith(compareBy { -it }).toList())
    println(listOf(3, 1).maxOfWith(compareBy { it }) { -it })
    println(listOf(3, 1).minOfWith(compareBy { it }) { -it })
    println(listOf(3, 1).maxOfWithOrNull(compareBy { it }) { -it })
    println(emptyList<Int>().minOfWithOrNull(compareBy { it }) { -it })
    println(arrayOf(3, 1).maxOfWith(compareBy { it }) { -it })
    println(intArrayOf(3, 1).minOfWith(compareBy { it }) { -it })
    println(mapOf(1 to 2).maxOfWith(compareBy { it }) { it.value })
    println("ab".maxOfWith(compareBy { it }) { it.code })
    println(seq().count())
    println(seq().orEmpty().count())
    println(seq().map { -it }.toSortedSet())
}

