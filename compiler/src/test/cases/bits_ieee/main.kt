import kotlin.math.nextDown
import kotlin.math.nextTowards
import kotlin.math.nextUp
import kotlin.math.sign
import kotlin.math.ulp
import kotlin.math.withSign

fun main() {
    println(3.5.withSign(-1.0))
    println((-3.5).withSign(1.0))
    println(2.0.withSign(-0.0))
    println(0.0.withSign(-2.0))
    println(5.0.withSign(-3))
    println(2.5f.withSign(-1f))

    println(1.0.ulp)
    println(0.0.ulp)
    println(1e300.ulp)
    println(Double.MAX_VALUE.ulp)
    println((-8.0).ulp)
    println(1f.ulp)
    println(Float.MAX_VALUE.ulp)
    println(1.0.nextUp())
    println(1.0.nextDown())
    println(2.0.nextDown())
    println((-2.0).nextUp())
    println((-1.0).nextDown())
    println(0.0.nextUp())
    println(0.0.nextDown())
    println(Double.MIN_VALUE.nextDown())
    println(1.0.nextTowards(2.0))
    println(1.0.nextTowards(0.0))
    println(1.0.nextTowards(1.0))
    println(1f.nextUp())
    println(1f.nextDown())
    println(100f.nextUp())
    println(0f.nextUp())
    println(1f.nextTowards(0f))

    println(1f.toBits())
    println((-2.5f).toBits())
    println(0.1f.toBits())
    println(Float.MAX_VALUE.toBits())
    println(Float.MIN_VALUE.toBits())
    println(1e-40f.toBits())
    println(Float.NaN.toBits())
    println(Float.POSITIVE_INFINITY.toBits())
    println(Float.NEGATIVE_INFINITY.toBits())
    println((-0f).toBits())
    println(Float.fromBits(1078530011))
    println(Float.fromBits(-1082130432))
    println(Float.fromBits(1))
    println(Float.fromBits(0x7f800000))
    println(Float.fromBits(0x7fc00000).isNaN())

    println(0x12345678.rotateLeft(8))
    println(0x12345678.rotateRight(8))
    println((-1).rotateLeft(5))
    println(1.rotateRight(1))
    println(0x12345678.rotateLeft(0))
    println(0x12345678.rotateLeft(32))
    println(0x12345678.rotateLeft(-4))
    println(1.rotateLeft(31))
    println(100.takeHighestOneBit())
    println((-5).takeHighestOneBit())
    println(0.takeHighestOneBit())
    println(96.takeLowestOneBit())
    println(Int.MIN_VALUE.takeLowestOneBit())
    println(0.takeLowestOneBit())
    println(0x80000000u.rotateLeft(1))
    println(3.sign)
    println((-2.5).sign)
}
