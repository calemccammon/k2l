data class Item(val name: String, val price: Int)

fun main() {
    val xs = listOf(5, 3, 8, 1, 9, 2)
    println(xs)
    println(xs.size)
    println(xs[0] + xs[xs.size - 1])
    println(xs.map { it * 2 })
    println(xs.filter { it % 2 == 1 })
    println(xs.sorted())
    println(xs.sortedDescending())
    println(xs.sum())
    println(xs.maxOrNull())
    println(xs.minOrNull())
    println(xs.average())
    println(xs.first() + xs.last())
    println(xs.any { it > 8 })
    println(xs.all { it > 0 })
    println(xs.none { it > 100 })
    println(xs.count { it > 3 })
    println(xs.indexOf(8))
    println(xs.contains(3))
    println(4 in xs)
    println(xs.take(2) + xs.drop(4))
    println(xs.reversed())
    println(xs.joinToString(", ", prefix = "<", postfix = ">"))
    println(xs.joinToString("-") { "n$it" })
    println(xs.fold(0) { acc, x -> acc + x })
    println(xs.reduce { a, b -> a * b })
    println(xs.firstOrNull { it > 100 })
    println(xs.find { it > 4 })
    println(listOf(1, 1, 2, 3, 3).distinct())
    println(xs.chunked(4))
    println(xs.zip(listOf("a", "b", "c")))
    println(xs.withIndex().map { (i, v) -> i * v })

    val items = listOf(Item("pen", 3), Item("book", 12), Item("cup", 5), Item("ink", 3))
    println(items.sortedBy { it.price }.map { it.name })
    println(items.sortedByDescending { it.price }.first().name)
    println(items.maxByOrNull { it.price })
    println(items.sumOf { it.price })
    println(items.groupBy { it.price })
    println(items.associateBy { it.name }["cup"])
    println(items.partition { it.price > 4 })
    println(items.map { it.name }.sorted())

    val m = mutableListOf<String>()
    m.add("b")
    m.add("c")
    m.add(0, "a")
    m += "d"
    println(m)
    m.removeAt(1)
    m.remove("d")
    println(m)
    m[0] = "z"
    println(m)
    println(m.isEmpty())
    m.clear()
    println(m.isEmpty())

    var total = 0
    for (x in xs) total += x
    println(total)
    for (i in xs.indices) if (i % 2 == 0) print("${xs[i]} ")
    println()
    for ((i, x) in xs.withIndex()) if (i < 2) print("$i:$x ")
    println()
    xs.forEach { if (it > 4) print("$it ") }
    println()
    xs.forEachIndexed { i, x -> if (i == 0) println("first is $x") }

    val nested = listOf(listOf(1, 2), listOf(3), listOf())
    println(nested.flatten())
    println(nested.flatMap { it.map { x -> x * 10 } })
    println(listOf(1, 2) == listOf(1, 2))
    println(List(4) { it * it })
    val arr = intArrayOf(3, 1, 2)
    arr[1] = 7
    println(arr.size)
    println(arr.toList())
    val words = arrayOf("x", "y")
    println(words.joinToString(""))
    println(listOf("a", null, "b").filterNotNull())
    val (a, b) = listOf(10, 20)
    println(a + b)
}
