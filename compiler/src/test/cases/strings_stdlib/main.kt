    val s = "Hello, World"
    println(s.substring(7))
    println(s.substring(0, 5))
    println(s[4])
    println(s.startsWith("Hell"))
    println(s.endsWith("x"))
    println(s.contains("lo, W"))
    println(s.indexOf("o"))
    println(s.lastIndexOf("o"))
    println(s.replace("l", "L"))
    println("a,b,,c".split(","))
    println("  padded  ".trim() + "|")
