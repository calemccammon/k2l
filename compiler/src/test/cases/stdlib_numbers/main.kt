import kotlin.math.*

fun ints() {
    println(Int.MAX_VALUE)
    println(Int.MIN_VALUE)
    println(255.toString(16))
    println(255.toString(2))
    println((-255).toString(16))
    println(10.toString(2))
    println(10.toByte())
    println(300.toByte())
    println(70000.toShort())
    println(3.9.toInt())
    println((-3.9).toInt())
    println(1e10.toInt())
    println(5L.toInt())
    println(0x7fffffff + 0)
    println(12345.toLong() * 1000)
    println(7.compareTo(9))
    println(9.compareTo(7))
    println(5.coerceIn(1, 3))
    println(10.countOneBits())
    println(8.countTrailingZeroBits())
    println(1.countLeadingZeroBits())
    println(0b1011.inv())
    println(5 xor 3)
    println(5 and 3)
    println(5 or 3)
    println(1 shl 4)
    println(-16 shr 2)
    println(-16 ushr 28)
    println(7.sign)
    println((-7).absoluteValue)
    println(10.toDouble() / 4)
    println(17 % 5)
    println(2 * 3 + 4)
    println(Int.MAX_VALUE.toLong() + 1)
}

fun chars() {
    println('a'.code)
    println(97.toChar())
    println('a' + 1)
    println('d' - 'a')
    println('a'.uppercaseChar())
    println('Z'.lowercaseChar())
    println('5'.digitToInt())
    println('f'.digitToInt(16))
    println('x'.digitToIntOrNull())
    println(7.digitToChar())
    println('a'.isLetter())
    println('1'.isDigit())
    println(' '.isWhitespace())
    println('A'.isUpperCase())
    println('a'.isLowerCase())
    println('_'.isLetterOrDigit())
    println('a'.compareTo('c'))
    println(('a'..'e').toList())
    println(('a'..'e').joinToString(""))
    println('c' in 'a'..'e')
    println('a'.toString() + 'b')
    println('x'.titlecase())
}

fun ranges() {
    println((1..5).sum())
    println((1..5).map { it * it })
    println((5 downTo 1).toList())
    println((1..10 step 3).toList())
    println((10 downTo 1 step 4).toList())
    println((1 until 5).toList())
    println((1..0).toList())
    println((1..5).reversed().toList())
    println((1..5).count())
    println((1..5).first)
    println((1..5).last)
    println((1..10 step 2).last)
    println(3 in 1..5)
    println(7 !in 1..5)
    println((1..5).contains(5))
    println((1..5).average())
    println((1..5).fold(1) { a, b -> a * b })
    println((1..3).toList().sumOf { it })
    println((1..5).filter { it % 2 == 1 })
    println((1..5).min())
    println((1..5).max())
    println((1..5).isEmpty())
    println((1..0).isEmpty())
    println((1.0..2.0).contains(1.5))
    println((1.0..2.0).endInclusive)
    println(1..5)
    println((1..5).step(2))
    println((1L..3L).toList())
    println((1..5).zip(6..10))
    println((1..4).associateWith { it * 2 })
    println((1..6).chunked(4))
    println((1..3).flatMap { a -> (1..a).map { a * 10 + it } })
    println((1..5).random(kotlin.random.Random(3)) in 1..5)
}

fun longs() {
    val big = 1234567890123L
    println(big)
    println(big + 1)
    println(big / 1000)
    println(big % 1000)
    println(big.toString().length)
    println(big > 5)
    println("123456789012".toLong())
    println(maxOf(big, 5L))
    println(big.toDouble())
    println(-big)
}

fun main() {
    ints()
    chars()
    ranges()
    longs()
}
