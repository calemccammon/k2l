import kotlin.math.*

fun basics() {
    println(abs(-7.5))
    println(abs(-7))
    println(sign(-3.0))
    println(sign(0.0))
    println(max(1.5, 2.5))
    println(min(3, 4))
    println(maxOf(1, 2, 3))
    println(minOf(5.0, 2.0, 9.0))
    println(sqrt(81.0))
    println(cbrt(27.0))
    println(hypot(3.0, 4.0))
    println(2.0.pow(10))
    println(2.0.pow(0.5))
    println(10.0.pow(-2))
    println(exp(0.0))
    println(ln(1.0))
    println(log10(1000.0))
    println(log2(8.0))
    println(log(8.0, 2.0))
    println(E)
    println(PI)
}

fun rounding() {
    println(floor(2.7))
    println(ceil(2.1))
    println(floor(-2.5))
    println(ceil(-2.5))
    println(round(2.5))
    println(round(3.5))
    println(round(-2.5))
    println(round(2.4))
    println(truncate(-2.7))
    println(2.7.roundToInt())
    println((-2.5).roundToInt())
    println(2.5.roundToInt())
    println(2.5.roundToLong())
    println(7.toDouble() / 2)
    println(7 / 2)
    println(-7 / 2)
    println(-7 % 3)
    println(7.mod(-3))
    println((-7).mod(3))
    println(-7.floorDiv(2))
    println((-7.5).mod(2.0))
    println(7.5 % 2)
    println(abs(-0.0))
}

fun trig() {
    println(sin(0.0))
    println(cos(0.0))
    println(tan(0.0))
    println(atan2(1.0, 1.0))
    println(atan(1.0))
    println(asin(1.0))
    println(acos(1.0))
    println(sinh(0.0))
    println(cosh(0.0))
    println(tanh(0.0))
    println((PI / 2).let { sin(it) })
    println(Math.toDegrees(PI))
    println(Math.toRadians(180.0))
}

fun special() {
    println(1.0 / 0.0)
    println(-1.0 / 0.0)
    println((0.0 / 0.0).isNaN())
    println(Double.NaN == Double.NaN)
    println(Double.POSITIVE_INFINITY.isInfinite())
    println(1.5.isFinite())
    println(Double.MAX_VALUE)
    println(Double.MIN_VALUE)
    println(sqrt(-1.0).isNaN())
    println(0.1 + 0.2)
    println(1e21)
    println(1e-5)
    println(123456789.0 * 10)
    println(100.0)
    println(1.0E7)
    println(12345678.9)
    println(1.0.compareTo(2.0))
    println(5.0.coerceIn(0.0, 3.0))
    println(5.coerceAtLeast(7))
    println(5.coerceAtMost(3))
    println(5.coerceIn(1..3))
}

fun main() {
    basics()
    rounding()
    trig()
    special()
}
