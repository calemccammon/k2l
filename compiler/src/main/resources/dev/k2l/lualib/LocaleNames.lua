    local decoded = {}

    local function lookup(kind, code)
        local names = decoded[kind]
        if names == nil then
            names = {}
            for key, name in data[kind]:gmatch("([^=\n]+)=([^\n]*)\n") do
                names[key] = name
            end
            decoded[kind] = names
        end
        return names[code]
    end

    -- the display locale must be English (or the root locale, which shows the English names too)
    local function checkDisplayLocale(inLocale)
        if inLocale ~= nil then
            local language = L.language(inLocale)
            if language ~= "en" and language ~= "" then
                error(__K2L_UnsupportedOperationException.new("display names are available in English only, not in " .. inLocale))
            end
        end
    end

    function N.language(tag, inLocale)
        checkDisplayLocale(inLocale)
        local code = L.language(tag)
        return lookup("languages", code) or code
    end

    function N.country(tag, inLocale)
        checkDisplayLocale(inLocale)
        local code = L.country(tag)
        return lookup("countries", code) or code
    end

    function N.script(tag, inLocale)
        checkDisplayLocale(inLocale)
        local code = tag:match("_#(%a+)$") or ""
        return lookup("scripts", code) or code
    end

    local function variantNames(tag)
        local names = {}
        for token in L.variant(tag):gmatch("[^_]+") do
            names[#names + 1] = lookup("variants", token) or token
        end
        return names
    end

    function N.variant(tag, inLocale)
        checkDisplayLocale(inLocale)
        return table.concat(variantNames(tag), ", ")
    end

    -- the extensions of the legacy locales ja_JP_JP and th_TH_TH, which the JDK lists as qualifiers
    local EXTENSIONS = {ja_JP_JP = "Japanese Calendar", th_TH_TH = "Thai Digits"}

    -- "Language (Script, Country, Variant)", as Locale.getDisplayName does
    function N.name(tag, inLocale)
        checkDisplayLocale(inLocale)
        local names = {}
        for _, name in ipairs({N.language(tag), N.script(tag), N.country(tag)}) do
            if name ~= "" then
                names[#names + 1] = name
            end
        end
        for _, name in ipairs(variantNames(tag)) do
            names[#names + 1] = name
        end
        if EXTENSIONS[tag] ~= nil then
            names[#names + 1] = EXTENSIONS[tag]
        end
        if #names <= 1 then
            return names[1] or ""
        end
        return names[1] .. " (" .. table.concat(names, ", ", 2) .. ")"
    end
