package dev.k2l.coverage

/**
 * The report: per [Area], every function or property name (its overloads together) as supported, partly supported
 * (some overloads or argument lists), unsupported or untested.
 */
class CoverageReport(private val areas: List<Area>, results: List<ApiResult>, private val mapped: (String) -> Boolean = { false }) {
    /** The overloads of one name (`Iterable.chunked`). */
    class Entry(val key: String, val results: List<ApiResult>) {
        private val tested = results.filter { it.status != Status.Untested }
        val status: Status = when {
            tested.isEmpty() -> Status.Untested
            tested.all { it.status == Status.Supported } -> Status.Supported
            tested.any { it.status == Status.Supported || it.status == Status.Partial } -> Status.Partial
            else -> Status.Unsupported
        }
        val supportedOverloads get() = tested.count { it.status == Status.Supported }
        val testedOverloads get() = tested.size
        val needsUtf16 get() = results.any { it.note == NEEDS_UTF16 }
        val note: String? get() = (tested.firstOrNull { it.status != Status.Supported } ?: results.firstOrNull())?.note
    }

    private val byArea: Map<String, List<Entry>> = results.groupBy { it.api.area }.mapValues { (_, rs) ->
        rs.groupBy { it.api.key }.map { (key, overloads) -> Entry(key, overloads) }.sortedBy { it.key }
    }

    private fun entries(area: Area) = byArea[area.name].orEmpty()

    private class Counts(entries: List<Entry>) {
        val supported = entries.count { it.status == Status.Supported }
        val partial = entries.count { it.status == Status.Partial }
        val unsupported = entries.count { it.status == Status.Unsupported }
        val untested = entries.count { it.status == Status.Untested }
        val tested = supported + partial + unsupported
        val overloads = entries.sumOf { it.testedOverloads }
        val supportedOverloads = entries.sumOf { it.supportedOverloads }

        /** Names fully supported, out of those tested. */
        val percent get() = percent(supported, tested)
        val overloadPercent get() = percent(supportedOverloads, overloads)

        private companion object {
            const val PERCENT = 100.0
        }

        private fun percent(n: Int, of: Int) = if (of == 0) "-" else "%.1f%%".format(java.util.Locale.ROOT, PERCENT * n / of)
    }

    fun summary(): String = buildString {
        appendLine("%-26s %9s %9s %9s %9s %8s %9s".format("area", "supported", "partial", "unsupp.", "untested", "names", "overloads"))
        for (area in areas) {
            val c = Counts(entries(area))
            appendLine(
                "%-26s %9d %9d %9d %9d %8s %9s".format(
                    area.name,
                    c.supported,
                    c.partial,
                    c.unsupported,
                    c.untested,
                    c.percent,
                    c.overloadPercent,
                ),
            )
        }
    }

    /** The unsupported and partly supported names, for `-PcoverageOnly`. */
    fun details(): String = buildString {
        for (area in areas) {
            appendLine("== ${area.name}")
            for (e in entries(area).filter { it.status == Status.Unsupported || it.status == Status.Partial }) {
                appendLine("  ${e.status.name.lowercase()} ${e.key} (${e.supportedOverloads}/${e.testedOverloads}): ${e.note}")
            }
        }
    }

    fun markdown(): String = buildString {
        appendLine("# Standard library coverage")
        appendLine()
        appendLine(
            "Generated by `./gradlew :compiler:stdlibCoverage` from the Kotlin stdlib and the JDK on k2l's classpath; don't edit by hand.",
        )
        appendLine()
        appendLine(
            "Each public function, property and constructor is called by a generated probe (a small Kotlin function) that k2l " +
                "transpiles in-process. A name is *supported* when every probe of every overload translates, *partial* when " +
                "some do, and *unsupported* when none does. Probes call operators and infix functions in their syntax, pass " +
                "lambdas as trailing lambdas, and try each function with only its required arguments and with all of them. " +
                "Names marked (utf16) translate only with `--strings utf16`. *Untested* names are deprecated, experimental " +
                "(opt-in), or could not be probed (the reason is listed). " +
                "Supporting a name here means k2l translates the call; the test cases in `compiler/src/test/cases` check " +
                "what it does against the JVM.",
        )
        appendLine()
        appendLine("| Area | Supported | Partial | Unsupported | Untested | Names supported | Overloads supported |")
        appendLine("|---|---:|---:|---:|---:|---:|---:|")
        for (area in areas) {
            val c = Counts(entries(area))
            appendLine(
                "| [${area.name}](#${anchor(area.name)}) | ${c.supported} | ${c.partial} | ${c.unsupported} | ${c.untested} | " +
                    "${c.percent} | ${c.overloadPercent} |",
            )
        }
        val all = Counts(areas.flatMap { entries(it) })
        appendLine(
            "| **All** | ${all.supported} | ${all.partial} | ${all.unsupported} | ${all.untested} | ${all.percent} | ${all.overloadPercent} |",
        )
        for (area in areas) section(area)
    }

    private fun StringBuilder.section(area: Area) {
        val entries = entries(area)
        val c = Counts(entries)
        appendLine()
        appendLine("## ${area.name}")
        appendLine()
        appendLine("${c.supported} of ${c.tested} names supported (${c.percent}), ${c.partial} partly; ${c.untested} untested.")
        list("Unsupported", entries.filter { it.status == Status.Unsupported }) { "`${it.key}`: ${it.note.orEmpty().escaped()}" }
        list("Partial", entries.filter { it.status == Status.Partial }) {
            "`${it.key}` (${it.supportedOverloads} of ${it.testedOverloads} overloads): ${it.note.orEmpty().escaped()}"
        }
        val supported = entries.filter { it.status == Status.Supported }
        if (supported.isNotEmpty()) {
            appendLine()
            appendLine("<details><summary>Supported (${supported.size})</summary>")
            appendLine()
            appendLine(supported.joinToString(", ") { "`${it.key}`" + if (it.needsUtf16) " (utf16)" else "" })
            appendLine()
            appendLine("</details>")
        }
        val untested = entries.filter { it.status == Status.Untested }
        if (untested.isNotEmpty()) {
            appendLine()
            appendLine("<details><summary>Untested (${untested.size})</summary>")
            appendLine()
            val (plain, probed) = untested.partition { it.note == DEPRECATED || it.note == EXPERIMENTAL }
            plain.groupBy {
                it.note!!
            }.toSortedMap().forEach { (why, es) -> appendLine("- $why: " + es.joinToString(", ") { "`${it.key}`" }) }
            probed.forEach { e ->
                val named = e.results.mapNotNull { it.api.callableId }.any(mapped)
                appendLine("- `${e.key}`: ${e.note.orEmpty().escaped()}" + if (named) " (named in k2l's mapping tables)" else "")
            }
            appendLine()
            appendLine("</details>")
        }
    }

    private fun StringBuilder.list(title: String, entries: List<Entry>, line: (Entry) -> String) {
        if (entries.isEmpty()) return
        appendLine()
        appendLine("### $title (${entries.size})")
        appendLine()
        entries.forEach { appendLine("- " + line(it)) }
    }

    private fun String.escaped() = replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;").replace("\n", " ")

    private companion object {
        const val DEPRECATED = "deprecated"
        const val EXPERIMENTAL = "experimental (opt-in)"
    }

    private fun anchor(title: String) = title.lowercase().replace(Regex("[^a-z0-9 -]"), "").replace(' ', '-')
}
